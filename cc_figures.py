SIDE = []


def side(fig_name, item, value):
    SIDE.append({"figure": fig_name, "item": item, "value": float(value)})


def fig1():
    import geopandas as gpd
    import matplotlib.cm as cm
    from matplotlib.colors import BoundaryNorm, ListedColormap
    from matplotlib.patches import Patch
    sma = gpd.read_file("exploratory/sma_boundaries.gpkg")
    d = pd.read_csv("census_based/smsa_density_census_2024.csv")
    d["sma"] = d["smsa_code"].apply(lambda c: str(c).zfill(4))
    sma = sma.merge(d[["sma", "physicians_per_100k"]], on="sma", how="left")

    # 6 quantile classes so the whole gradient is visible (equal-count bins)
    vals = sma["physicians_per_100k"].dropna().values
    k = 6
    edges = np.unique(np.quantile(vals, np.linspace(0, 1, k + 1)))
    for _i, _e in enumerate(edges):
        side("Fig1_density_map_2024", f"quantile_edge_{_i}", _e)
    side("Fig1_density_map_2024", "n_circles_mapped", int(len(vals)))
    # magma sampled across a controlled span: 6 classes with monotonically rising
    # luminance (dark -> light), so they stay distinct in colour AND in greyscale/B&W,
    # while avoiding the near-black and near-white extremes that wash out on the page.
    base = cm.get_cmap("magma")
    colours = [base(t) for t in np.linspace(0.08, 0.90, len(edges) - 1)]
    cmap = ListedColormap(colours)
    norm = BoundaryNorm(edges, cmap.N)

    fig, ax = plt.subplots(figsize=(6.4, 6.8))
    sma.plot(column="physicians_per_100k", cmap=cmap, norm=norm, linewidth=0.15,
             edgecolor="white", ax=ax, missing_kwds={"color": "#d9d9d9"})
    ax.set_axis_off()
    ax.set_aspect(1.24)
    # discrete legend with quantile ranges
    handles = []
    for i in range(len(edges) - 1):
        lab = f"{edges[i]:.0f}–{edges[i+1]:.0f}"
        handles.append(Patch(facecolor=colours[i], edgecolor="white", label=lab))
    leg = ax.legend(handles=handles, title="Physicians per 100 000 (2024)",
                    loc="lower right", bbox_to_anchor=(1.0, 0.03),
                    fontsize=11, title_fontsize=12.5, frameon=False,
                    handlelength=1.5, handleheight=1.4, labelspacing=0.5,
                    borderpad=0.3)
    leg.get_title().set_fontweight("bold")

    # ---- metro insets -------------------------------------------------------------
    # The top class spans 327-1270, and every circle in it is geographically tiny, so at
    # national scale the map cannot show its own extremes. Two magnifiers fix that.
    #
    # They share `cmap` and `norm` with the main map -- the SAME objects, not a copy -- so
    # an inset cannot re-scale to its own range and disagree in colour with the national
    # map. One legend serves both. Extents come from the polygons of the constituent
    # circles, never from typed coordinates, so they follow the geometry if it is rebuilt.
    from matplotlib.patches import Rectangle, ConnectionPatch
    from shapely.geometry import box
    # Some circles are archipelagos: Tokyo's Toshosho covers the Izu and Ogasawara islands
    # out to 20N/154E, so its bounding box is 37x the median and swallows the Pacific. Taken
    # naively, Greater Tokyo's extent became mostly ocean and the inset showed almost
    # nothing. Identify them by how little of their own bounding box they fill -- scattered
    # islands fill almost none, whereas Hokkaido's genuinely large circles fill about half.
    # Seven circles fall below 0.05 and all seven are archipelagos. They are excluded from
    # the EXTENT CALCULATION ONLY; every one of the 330 is still drawn on the national map.
    _b = sma.geometry.bounds
    _fill = sma.geometry.area / ((_b.maxx - _b.minx) * (_b.maxy - _b.miny))
    _mainland = sma[_fill >= 0.05]
    side("Fig1_density_map_2024", "circles_excluded_from_inset_extent",
         int((_fill < 0.05).sum()))
    _panels = []
    INSETS = [("Tokyo", ("11", "12", "13", "14"), [0.015, 0.615, 0.275, 0.215]),
              ("Keihanshin", ("26", "27", "28"), [0.015, 0.360, 0.275, 0.215])]
    for _name, _prefs, _rect in INSETS:
        _sub = _mainland[_mainland["sma"].str[:2].isin(_prefs)]
        x0, y0, x1, y1 = _sub.total_bounds
        _mx, _my = (x1 - x0) * 0.04, (y1 - y0) * 0.04
        x0, x1, y0, y1 = x0 - _mx, x1 + _mx, y0 - _my, y1 + _my
        side("Fig1_density_map_2024", f"inset_{_name}_n_circles", int(len(_sub)))
        side("Fig1_density_map_2024", f"inset_{_name}_max_density",
             float(_sub["physicians_per_100k"].max()))
        axi = fig.add_axes(_rect)
        _panels.append((_name, axi))
        # Select the polygons that fall in the window rather than drawing all 330 and
        # letting the axis limits hide the rest: clipping by limits still embeds the whole
        # country's geometry in each inset and tripled the PDF. Colours are unaffected --
        # cmap and norm are the main map's own objects, so class boundaries are identical.
        sma.cx[x0:x1, y0:y1].plot(column="physicians_per_100k", cmap=cmap, norm=norm,
                                  linewidth=0.15, edgecolor="white", ax=axi,
                                  missing_kwds={"color": "#d9d9d9"})
        axi.set_xlim(x0, x1); axi.set_ylim(y0, y1)
        axi.set_aspect(1.24); axi.set_xticks([]); axi.set_yticks([])
        for _side, _s in axi.spines.items():
            # rcParams switch off top and right globally, which left the panels looking
            # like open brackets rather than framed magnifiers
            _s.set_visible(True)
            _s.set_edgecolor("#1b4965"); _s.set_linewidth(0.9)
        # the label belongs to the panel, not to the map -- it sat on top of Honshu before
        axi.set_title(_name, fontsize=11, fontweight="bold", color="#1b4965",
                      loc="left", pad=2.5)
        # locator box on the national map, joined to its panel by a leader so the pairing
        # is readable; without it two boxes and two panels are four unlinked objects
        ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fill=False,
                               edgecolor="#1b4965", linewidth=0.8, zorder=6))
        fig.add_artist(ConnectionPatch(
            xyA=(x0, (y0 + y1) / 2), coordsA=ax.transData,
            xyB=(1.0, 0.5), coordsB=axi.transAxes,
            color="#1b4965", linewidth=0.7, linestyle=(0, (4, 2)), zorder=5))

    # An inset panel laid over the landmass hides the data it is meant to explain, and
    # eyeballing it is how the first attempt shipped with Keihanshin covering Chugoku.
    # Check it: map each panel's rectangle into the national map's data coordinates and
    # require that it intersects no circle.
    fig.canvas.draw()
    _inv = ax.transData.inverted()
    for _name, _axi in _panels:
        _bb = _axi.get_window_extent()
        (_dx0, _dy0), (_dx1, _dy1) = _inv.transform([[_bb.x0, _bb.y0], [_bb.x1, _bb.y1]])
        _hits = sma.sindex.query(box(_dx0, _dy0, _dx1, _dy1), predicate="intersects")
        if len(_hits):
            raise AssertionError(
                f"inset panel {_name} overlaps {len(_hits)} circle(s) on the national map")
    side("Fig1_density_map_2024", "inset_panels_overlapping_circles", 0)

    save_pub(fig, "Fig1_density_map_2024")


# ============================================================
# FIG 3 — Core mechanism: density choropleth + net service-flow arrows
# Source: geometry + od_matrix_2024 net flows + census density
# Net flows come from exploratory A logic but recomputed ONLY as flow geometry,
# headline numbers (quintile table) are NOT re-derived here.
