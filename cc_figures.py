def fig3():
    """Single-panel inter-quintile net service-flow schematic: Q5 (highest density)
    exporting to Q1-Q4, arrow width proportional to each quintile's net gain
    (Table 1, frozen values). Nodes coloured by mean density."""
    import matplotlib.cm as cm
    from matplotlib.colors import Normalize

    # Read from the SAME output Table 2 is bound to, so the caption's claim that "values
    # correspond to Table 2" is enforced rather than asserted. These were hardcoded.
    _t2 = pd.read_csv("outputs/audit/j02_table_2.csv", encoding="utf-8-sig")
    Q = {f"Q{int(r.quintile)}": dict(dens=float(r.mean_density),
                                     net=float(r.total_net_flow))
         for _, r in _t2.iterrows()}
    for _q, _v in Q.items():
        side("Fig4_flow_mechanism", f"{_q}_mean_density", _v["dens"])
        side("Fig4_flow_mechanism", f"{_q}_net_flow", _v["net"])
    def flow(v):
        """A net flow as Table 1 prints it: signed integer, thousands separator, real minus.

        Three things were wrong with format(v, '+,') here. The values arrive from
        j02_table_2.csv as floats, so every label read "+2,633.0" -- a tenth of a physician,
        which is not a quantity that exists. The minus was ASCII hyphen where the table sets a
        LaTeX minus, so Fig 1 and Table 1 printed the same number with different signs. And the
        density labels beside them had already moved to one decimal to match the table, which
        left the figure using two conventions at once.

        The assertion is not decoration: these are head-counts, and if one ever arrives
        non-integral the right answer is to stop, not to round it away silently.
        """
        assert float(v).is_integer(), f"net flow {v!r} is not a whole number of physicians"
        return f"{int(v):+,}".replace("-", "−")

    norm = Normalize(vmin=140, vmax=400)
    cmap = cm.get_cmap("viridis")

    fig, axs = plt.subplots(figsize=(6.6, 5.4))
    pos = {"Q1": (0.15, Q["Q1"]["dens"]), "Q2": (1.05, Q["Q2"]["dens"]),
           "Q3": (1.95, Q["Q3"]["dens"]), "Q4": (2.85, Q["Q4"]["dens"]),
           "Q5": (1.5, Q["Q5"]["dens"])}
    maxgain = max(Q[q]["net"] for q in ["Q1", "Q2", "Q3", "Q4"])
    x5, y5 = pos["Q5"]
    for q in ["Q1", "Q2", "Q3", "Q4"]:
        x1, y1 = pos[q]
        frac = Q[q]["net"] / maxgain
        ar = FancyArrowPatch((x5, y5 - 14), (x1, y1 + 14), arrowstyle="-|>",
                             mutation_scale=10 + 12*frac, lw=1 + 6*frac,
                             color="#b00020", alpha=0.8,
                             connectionstyle="arc3,rad=0.18", zorder=3, capstyle="round")
        axs.add_patch(ar)
        xm, ym = (x5 + x1)/2, (y5 + y1)/2
        # Round 43-r52 (2026-10-12): 7 -> 8 pt and the node notes 6.5 -> 8 pt, round 51's redraw
        # carried into the closure; 14 text runs had been below the 8 pt floor.
        axs.text(xm, ym, flow(Q[q]['net']), fontsize=8, color="#b00020",
                 ha="center", va="center", zorder=4,
                 bbox=dict(boxstyle="round,pad=0.1", fc="white", ec="none", alpha=0.85))
    for q, (x, y) in pos.items():
        axs.scatter([x], [y], s=640, c=[cmap(norm(Q[q]["dens"]))], edgecolor="k",
                    linewidth=0.7, zorder=5)
        axs.text(x, y, q, fontsize=8.5, fontweight="bold", ha="center", va="center",
                 color="white" if Q[q]["dens"] < 300 else "black", zorder=6)
        # One decimal, because Table 1 prints these same five means at one decimal (153.6,
        # 195.0, 225.3, 268.1, 392.0). At :.0f the node read 154 against the table's 153.6
        # and a reader had to decide whether that was the same number.
        lbl = f"{Q[q]['dens']:.1f}/100k\nnet {flow(Q[q]['net'])}"
        if q == "Q5":
            axs.annotate(lbl, (x, y), xytext=(22, 0), textcoords="offset points",
                         ha="left", va="center", fontsize=8)
        else:
            axs.annotate(lbl, (x, y), xytext=(0, -28), textcoords="offset points",
                         ha="center", va="top", fontsize=8)
    axs.set_xlim(-0.8, 4.0)
    axs.set_ylim(120, 425)
    axs.set_ylabel("Mean physician density (per 100 000)")
    axs.set_xticks([])
    axs.spines["bottom"].set_visible(False)
    # Round 50 §2: no title drawn into the graphic. The journal (International Journal of Health
    # Geographics) wants the figure title and legend in the manuscript's Figure legends, not in
    # the image file; the title that stood here is the first sentence of that legend.
    fig.tight_layout()
    save_pub(fig, "Fig4_flow_mechanism")


